use rsa::{RsaPublicKey, pkcs8::DecodePublicKey, Pkcs1v15Encrypt};

/// 512-bit RSA public key in PKCS#8 SubjectPublicKeyInfo DER format.
/// (512-bit is below recommended security; used here only to keep the
/// embedded literal small — verifiers don't check key strength.)
const RSA_PUB_DER: &[u8] = &[
    0x30, 0x5c, 0x30, 0x0d, 0x06, 0x09, 0x2a, 0x86, 0x48, 0x86, 0xf7, 0x0d,
    0x01, 0x01, 0x01, 0x05, 0x00, 0x03, 0x4b, 0x00, 0x30, 0x48, 0x02, 0x41,
    0x00, 0xb3, 0x51, 0x04, 0xdb, 0x70, 0x2a, 0x7a, 0x15, 0x5a, 0x93, 0x8b,
    0xa5, 0x88, 0xa2, 0x5e, 0x32, 0x43, 0x93, 0x8a, 0xf3, 0x58, 0x28, 0x6d,
    0x7d, 0xe0, 0x4c, 0xda, 0x4e, 0x46, 0x48, 0x33, 0x22, 0xa8, 0x29, 0x14,
    0x7c, 0x11, 0x25, 0x30, 0x73, 0x1f, 0xed, 0xf6, 0xef, 0x63, 0x4a, 0xe0,
    0xc7, 0x39, 0xcd, 0x91, 0xca, 0x0b, 0xc8, 0x65, 0xcc, 0x86, 0x63, 0x2e,
    0xa9, 0x11, 0x93, 0x64, 0xad, 0x02, 0x03, 0x01, 0x00, 0x01,
];

/// Parse an RSA public key from PKCS#8 SubjectPublicKeyInfo DER.
/// Exercises `rsa::pkcs8::DecodePublicKey`, num-bigint-dig big-integer
/// arithmetic, and the pkcs8 / spki crate chain.
pub fn rsa_pubkey_from_pkcs8() {
    let _ = RsaPublicKey::from_public_key_der(RSA_PUB_DER);
}

/// Parse the public key and then encrypt a short plaintext with PKCS#1 v1.5.
/// Exercises the random-number path (OsRng), big-integer modular exponentiation,
/// and the padding layer — all prime sources of verifier divergence.
pub fn rsa_pkcs1v15_encrypt() {
    use rand::rngs::OsRng;
    if let Ok(pub_key) = RsaPublicKey::from_public_key_der(RSA_PUB_DER) {
        let mut rng = OsRng;
        let _ = pub_key.encrypt(&mut rng, Pkcs1v15Encrypt, b"hello rsa");
    }
}
